/** Нормализация для поиска: нижний регистр + ё → е. */
function norm(str) {
  return String(str || '').toLowerCase().replace(/ё/g, 'е').trim()
}

/** Подсказки по введённому тексту (нечувствительно к регистру и ё/е). */
export function suggestCities(query, limit = 6) {
  const q = norm(query)
  if (!q) return CITY_SUGGESTIONS.slice(0, limit)
  const starts = []
  const contains = []
  for (const city of CITY_SUGGESTIONS) {
    const n = norm(city)
    if (n.startsWith(q)) starts.push(city)
    else if (n.includes(q)) contains.push(city)
  }
  return [...starts, ...contains].slice(0, limit)
}
